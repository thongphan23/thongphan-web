import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

import { validateReadingPackages } from './validate-reading-rights.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const defaultContentDir = join(root, 'content/readings')
const defaultOutputFile = join(root, 'lib/readings-data.generated.ts')

const publicImage = (candidate) => ({
  src: candidate.publicPath,
  alt: candidate.alt,
  caption: candidate.caption,
  credit: candidate.credit,
  checksum: candidate.checksum,
  license: candidate.license,
})

const publicReading = ({ article, rights, imagePack }) => {
  const reading = {
    slug: article.slug,
    title: article.title,
    description: article.description,
    author: article.author,
    source: article.source,
    sourceUrl: article.sourceUrl,
    sourcePublishedAt: article.sourcePublishedAt,
    translator: article.translator,
    editor: article.editor,
    translatedAt: article.translatedAt,
    lastReviewedAt: article.lastReviewedAt,
    rightsStatus: article.rightsStatus,
    minutes: article.minutes,
    topics: article.topics,
    intent: article.intent,
    durationBand: article.durationBand,
    readingPath: article.readingPath,
    coreIdea: article.coreIdea,
    whyRead: article.whyRead,
    reflection: article.reflection,
    authorProfile: article.authorProfile,
    contentContext: article.contentContext,
    contentChecksum: article.contentChecksum,
    contentVersion: article.contentVersion,
    publicationMode: rights.publicationMode,
    images: imagePack.candidates.filter((candidate) => candidate.status === 'ready').map(publicImage),
    audio: [],
  }

  if (rights.publicationMode === 'full') reading.sections = article.sections
  return reading
}

export function generateTypeScript(readings) {
  return `// AUTO-GENERATED by scripts/generate-readings-data.mjs
// Run \`npm run generate-readings\` to regenerate
// DO NOT EDIT MANUALLY

import type { ReadingArticle } from './readings'

export const generatedReadings: ReadingArticle[] = ${JSON.stringify(readings, null, 2)}
`
}

export async function generateReadingsData({
  contentDir = defaultContentDir,
  outputFile = defaultOutputFile,
} = {}) {
  const packages = await validateReadingPackages({ contentDir })
  const readings = packages
    .filter(({ rights }) => rights.publicationMode !== 'blocked')
    .map(publicReading)
    .sort((left, right) => left.slug.localeCompare(right.slug, 'en'))

  await mkdir(dirname(outputFile), { recursive: true })
  await writeFile(outputFile, generateTypeScript(readings), 'utf8')
  return readings
}

const isMain = process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url

if (isMain) {
  const readings = await generateReadingsData()
  console.log(`Generated ${readings.length} public reading summaries in ${defaultOutputFile}`)
}
