import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { contentSha256, stableJsonStringify } from './migrate-brain2-lessons.mjs'

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url))
const DEFAULT_CONTENT_DIR = resolve(SCRIPT_DIR, '../content/brain2')
const DEFAULT_OUTPUT_FILE = resolve(SCRIPT_DIR, '../lib/brain2/brain2-data.generated.ts')

const META_KEYS = [
  'schemaVersion',
  'day',
  'slug',
  'week',
  'access',
  'title',
  'promise',
  'objective',
  'estimatedMinutes',
  'preview',
  'sourceFragmentSha256',
  'contentSha256',
  'migratedAt',
  'editorialState',
]
const PROTECTED_MANIFEST_KEYS = [...META_KEYS, 'storageKey']
const PUBLIC_PACKAGE_KEYS = ['meta', 'reason', 'blocks', 'deliverable', 'checklist']

const exactKeys = (value, expected, scope) => {
  if (!value || typeof value !== 'object' || Array.isArray(value)) {
    throw new Error(`${scope} must be an object`)
  }
  const actual = Object.keys(value).sort()
  const wanted = [...expected].sort()
  if (actual.length !== wanted.length || actual.some((key, index) => key !== wanted[index])) {
    throw new Error(`${scope} contains an unexpected or missing field`)
  }
}

const readJson = async (filename) => JSON.parse(await readFile(filename, 'utf8'))

const publicMeta = (record) => Object.fromEntries(META_KEYS.map((key) => [key, record[key]]))

function validateManifest(manifest) {
  exactKeys(manifest, ['schemaVersion', 'releaseId', 'migratedAt', 'source', 'counts', 'lessons'], 'manifest')
  if (manifest.schemaVersion !== 1 || !Array.isArray(manifest.lessons) || manifest.lessons.length !== 21) {
    throw new Error('manifest must contain exactly 21 lessons')
  }

  return manifest.lessons.map((record, index) => {
    const day = index + 1
    const access = day <= 7 ? 'public' : 'conan-maker'
    exactKeys(record, access === 'public' ? META_KEYS : PROTECTED_MANIFEST_KEYS, `manifest day ${day}`)
    if (
      record.day !== day ||
      record.slug !== `ngay-${String(day).padStart(2, '0')}` ||
      record.week !== Math.ceil(day / 7) ||
      record.access !== access
    ) {
      throw new Error(`manifest day ${day} metadata is inconsistent`)
    }
    return publicMeta(record)
  })
}

function renderGeneratedModule(metadata, publicLessons) {
  return `// Generated by scripts/generate-brain2-data.mjs. Do not edit by hand.\n` +
    `import type { Brain2LessonMeta, Brain2LessonPackage } from './lesson-contract'\n\n` +
    `export const BRAIN2_LESSON_METADATA = ${JSON.stringify(metadata, null, 2)} as const satisfies readonly Brain2LessonMeta[]\n\n` +
    `export const BRAIN2_PUBLIC_LESSONS = ${JSON.stringify(publicLessons, null, 2)} as const satisfies Readonly<Record<string, Brain2LessonPackage>>\n`
}

export async function generateBrain2Data({
  contentDir = DEFAULT_CONTENT_DIR,
  outputFile = DEFAULT_OUTPUT_FILE,
} = {}) {
  const manifest = await readJson(join(contentDir, 'manifest.json'))
  const metadata = validateManifest(manifest)
  const publicLessons = {}

  for (const meta of metadata.slice(0, 7)) {
    const lesson = await readJson(join(contentDir, 'public', `${meta.slug}.json`))
    exactKeys(lesson, PUBLIC_PACKAGE_KEYS, `public package ${meta.slug}`)
    exactKeys(lesson.meta, META_KEYS, `public package ${meta.slug} meta`)
    if (stableJsonStringify(lesson.meta) !== stableJsonStringify(meta)) {
      throw new Error(`public package ${meta.slug} metadata does not match manifest`)
    }
    if (contentSha256(lesson) !== meta.contentSha256) {
      throw new Error(`public package ${meta.slug} checksum mismatch`)
    }
    publicLessons[meta.slug] = lesson
  }

  await writeFile(outputFile, renderGeneratedModule(metadata, publicLessons), 'utf8')
  return { metadata, publicLessons }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await generateBrain2Data()
  console.log('Brain2 public data generated: lessons=21 publicBodies=7 protectedBodies=0')
}
